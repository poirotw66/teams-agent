def seed_canonical_eval_set():
    print(f"Starting Golden Eval Set seed. Target count: {len(CANONICAL_CASES)} cases...")

    data_dir = REPO_ROOT / "data" / "ops" / "evaluations"
    data_dir.mkdir(parents=True, exist_ok=True)
    store_file = data_dir / "golden_evals.json"

    repo = FileEvaluationRepository(store_file)
    svc = EvaluationService(repo, default_tenant_id="local-development")

    created_rev_ids = []

    for idx, item in enumerate(CANONICAL_CASES, start=1):
        crit_items = (
            (CriterionItem(criterion_id="crit_1", description=item["fact"], is_mandatory=True),)
            if item["fact"]
            else ()
        )
        criteria = EvaluationCriteria(
            required_facts=crit_items,
            reference_answer=item["ref"] if item["ref"] else None,
        )
        evidence = (
            (
                EvidenceRequirement(
                    group_id="primary",
                    items=(
                        EvidenceItem(
                            evidence_id=f"ev_{idx}",
                            source_type=item["src_type"] if item["src_type"] in ("FAQ", "DOCUMENT") else "OTHER",
                            source_id=item["src_id"],
                            version_id="v1",
                        ),
                    ),
                ),
            )
            if item["behavior"] == "ANSWER_WITH_CITATION"
            else ()
        )
        provenance = ProvenanceSpec(
            source_type=item["src_type"],
            source_id=item["src_id"],
            source_version_id="v1",
        )

        res = svc.create_case(
            title=item["title"],
            query=item["query"],
            owner_unit_id=item["owner"],
            behavior=item["behavior"],
            criteria=criteria,
            evidence=evidence,
            tags=(item["tag"], "canonical"),
            criticality=item["criticality"],
            provenance=provenance,
            actor=KADMIN,
        )
        r_id = res["revision"]["revision_id"]

        # Submit revision
        svc.submit_revision(r_id, expected_etag=1, actor=KADMIN)

        # Approve revision with independent Service Owner
        svc.review_revision(
            r_id,
            approve=True,
            reason="Canonical Golden Eval Set approval for Phase GE-1 baseline",
            expected_etag=2,
            actor=SOWNER,
        )
        created_rev_ids.append(r_id)

    print(f"Created and approved {len(created_rev_ids)} canonical eval cases.")

    # Create Canonical Eval Set
    eval_set = svc.create_set(
        name="標準驗收題庫 (Canonical Golden Eval Set)",
        owner_unit_ids=("IT Service Desk", "HR", "General Administration"),
        purpose="DEVELOPMENT",
        description="全行標準金標驗收集：涵蓋問答引用、需求澄清、安全拒答/權限、多來源綜合與派工工具。",
        actor=KADMIN,
    )["eval_set"]
    set_id = eval_set["set_id"]
    print(f"Created Eval Set: {eval_set['name']} ({set_id})")

    # Create Draft Set Version
    draft_ver = svc.create_set_version_draft(
        set_id,
        case_revision_ids=tuple(created_rev_ids),
        actor=KADMIN,
    )["version"]
    ver_id = draft_ver["set_version_id"]

    # Publish Set Version
    pub_ver = svc.publish_set_version(
        ver_id,
        expected_etag=draft_ver["etag"],
        actor=SOWNER,
    )["version"]

    print(f"Successfully published Golden Eval Set version v{pub_ver['version']}!")
    print(f"Manifest Hash: {pub_ver['manifest_hash']}")
    print(f"Total Cases: {pub_ver['coverage_stats']['total_cases']}")
    print(f"Coverage by Behavior: {pub_ver['coverage_stats']['by_behavior']}")
    print(f"Coverage by Criticality: {pub_ver['coverage_stats']['by_criticality']}")
    print(f"Saved to: {store_file}")


if __name__ == "__main__":
    seed_canonical_eval_set()
